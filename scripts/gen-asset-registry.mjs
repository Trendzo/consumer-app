#!/usr/bin/env node
/**
 * Generate the bundled-asset registry from whatever is actually in `assets/`.
 *
 * The Home CMS lets an admin point a tile at either uploaded art (a URL) or art already inside
 * the app binary (an "asset key"). Metro can only resolve `require()` with a literal path, so
 * the key → require map has to exist as real source — it cannot be built at runtime from a
 * string. Hand-maintaining ~145 entries would rot within a week, so it is generated.
 *
 * Two outputs:
 *   src/content/assets.registry.ts  — the map the app resolves keys through. GENERATED; do not
 *                                     edit. The resolver that uses it lives in content/media.ts,
 *                                     which is hand-written precisely so regenerating is safe.
 *   src/content/asset-manifest.json — the same list as data, for the backend to seed `cms_assets`
 *                                     from so the admin picker can list and preview these.
 *
 * Keys are the path under assets/ minus the extension: `banners/her-new1`, `reels/female1`.
 *
 * Run: node scripts/gen-asset-registry.mjs
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, '..');
const ASSETS = join(APP_ROOT, 'assets');
const OUT_DIR = join(APP_ROOT, 'src', 'content');

const IMAGE_EXT = new Set(['.webp', '.png', '.jpg', '.jpeg']);
const VIDEO_EXT = new Set(['.mp4']);

/**
 * App chrome, not content. Icons and fonts are referenced directly by the components that own
 * them and would only be noise in a merchandising picker.
 */
const SKIP_DIRS = new Set(['icons', 'fonts']);
const SKIP_FILES = new Set([
  'adaptive-icon.png',
  'icon.png',
  'favicon.png',
  'splash-icon.png',
  'flash-sale.json',
]);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const rel = relative(ASSETS, full).split('\\').join('/');
    if (statSync(full).isDirectory()) {
      if (SKIP_DIRS.has(entry)) continue;
      walk(full, out);
      continue;
    }
    if (SKIP_FILES.has(entry)) continue;
    const dot = entry.lastIndexOf('.');
    if (dot < 0) continue;
    const ext = entry.slice(dot).toLowerCase();
    const kind = IMAGE_EXT.has(ext) ? 'image' : VIDEO_EXT.has(ext) ? 'video' : null;
    if (!kind) continue;
    out.push({
      key: rel.slice(0, rel.length - ext.length),
      file: rel,
      kind,
      // Top-level folder, or 'root' for the loose files (home.webp, vr-try-on.webp, …).
      category: rel.includes('/') ? rel.slice(0, rel.indexOf('/')) : 'root',
    });
  }
  return out;
}

const assets = walk(ASSETS).sort((a, b) => a.key.localeCompare(b.key));

const entries = assets
  .map((a) => `  '${a.key}': require('../../assets/${a.file}'),`)
  .join('\n');

const registry = `// GENERATED by scripts/gen-asset-registry.mjs — do not edit by hand.
// Re-run after adding or removing anything under assets/:
//   node scripts/gen-asset-registry.mjs
//
// Maps a CMS asset key to the bundled art it names. Metro needs a literal path inside
// require(), which is the whole reason this file is generated rather than computed at runtime.
// The resolver that reads it is in ./media.ts (hand-written, safe across regenerations).

export const ASSET_REGISTRY: Record<string, number> = {
${entries}
};

export type AssetKey = keyof typeof ASSET_REGISTRY;

/** ${assets.length} assets, ${new Set(assets.map((a) => a.category)).size} categories. */
export const ASSET_KEYS = Object.keys(ASSET_REGISTRY);
`;

writeFileSync(join(OUT_DIR, 'assets.registry.ts'), registry, 'utf8');
writeFileSync(
  join(OUT_DIR, 'asset-manifest.json'),
  `${JSON.stringify(
    assets.map(({ key, category, kind }) => ({ key, category, kind })),
    null,
    2,
  )}\n`,
  'utf8',
);

const byCategory = assets.reduce((acc, a) => {
  acc[a.category] = (acc[a.category] ?? 0) + 1;
  return acc;
}, {});
console.log(`Wrote ${assets.length} assets to src/content/`);
for (const [cat, n] of Object.entries(byCategory).sort()) console.log(`  ${cat.padEnd(20)} ${n}`);
